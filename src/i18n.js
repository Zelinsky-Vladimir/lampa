  const LANGS = [
    { id: 'en', name: 'English' },
    { id: 'ru', name: 'Русский' },
    { id: 'fr', name: 'Français' },
    { id: 'de', name: 'Deutsch' },
    { id: 'es', name: 'Español' },
  ];

  let lang = 'en';

  function detect() {
    for (const l of navigator.languages || [navigator.language || 'en']) {
      const id = String(l).slice(0, 2).toLowerCase();
      if (STRINGS[id]) return id;
    }
    return 'en';
  }

  function setLang(id) {
    lang = STRINGS[id] ? id : detect();
    document.documentElement.lang = lang;
  }

  function t(key, params) {
    let s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    return s;
  }

  // Статические подписи в HTML: data-i18n (текст), data-i18n-title, -placeholder, -aria.
  function apply(root) {
    const scope = root || document;
    for (const el of scope.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
    for (const el of scope.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
    for (const el of scope.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
    for (const el of scope.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  }

  global.I18n = {
    t,
    setLang,
    apply,
    LANGS,
    get lang() {
      return lang;
    },
  };
